#!/usr/bin/env python3
"""Rewrite src/languages.rs with the language breakdown of a GitHub user's repos.

Sums the bytes per language (GitHub's own count, from /repos/{repo}/languages)
over the user's public repos, leaving out forks, archived repos and anything in
EXCLUDE. The top languages get their own bar segment; the rest become "Other".

Run by .github/workflows/languages.yml every week. To run it by hand:

    GITHUB_TOKEN=... python3 scripts/update_languages.py

Standard library only, so the workflow needs no installs.
"""

import json
import os
import sys
import urllib.request
from pathlib import Path

USER = "x7lex"
EXCLUDE = {"x7lex"}  # The profile README repo has no code
TOP = 4  # Languages shown on their own; the rest are grouped as "Other"

# Bar colours, tuned to read on the dark panel. Unlisted languages use FALLBACK
COLORS = {
    "Python": "#e8c547",
    "Rust": "#dea584",
    "TypeScript": "#5a9be6",
    "JavaScript": "#f1e05a",
    "CSS": "#a77bdc",
    "HTML": "#e34c26",
    "Java": "#ed8b00",
    "Shell": "#89e051",
    "Go": "#00add8",
    "C": "#a8b9cc",
    "C++": "#f34b7d",
    "Lua": "#6c78e0",
}
FALLBACK = "#6b7280"

OUT = Path(__file__).resolve().parent.parent / "src" / "languages.rs"


def get(path):
    req = urllib.request.Request(
        f"https://api.github.com/{path}",
        headers={"Accept": "application/vnd.github+json", "User-Agent": "languages-script"},
    )
    if token := os.environ.get("GITHUB_TOKEN"):
        req.add_header("Authorization", f"Bearer {token}")
    with urllib.request.urlopen(req) as res:
        return json.load(res)


def fetch():
    repos = [
        r for r in get(f"users/{USER}/repos?type=owner&per_page=100")
        if not (r["fork"] or r["archived"] or r["private"] or r["name"] in EXCLUDE)
    ]
    totals = {}
    for r in repos:
        for lang, size in get(f"repos/{r['full_name']}/languages").items():
            totals[lang] = totals.get(lang, 0) + size
    return totals, len(repos)


def shares(totals):
    """Top languages plus "Other", as percentages with one decimal that add up to 100."""
    total = sum(totals.values())
    ranked = sorted(totals.items(), key=lambda kv: kv[1], reverse=True)
    rows = [(name, size) for name, size in ranked[:TOP]]
    rest = sum(size for _, size in ranked[TOP:])
    if rest:
        rows.append(("Other", rest))
    # Largest-remainder rounding to tenths, so the bar always fills exactly
    exact = [size * 1000 / total for _, size in rows]
    tenths = [int(x) for x in exact]
    by_remainder = sorted(range(len(rows)), key=lambda i: exact[i] - tenths[i], reverse=True)
    for i in by_remainder[: 1000 - sum(tenths)]:
        tenths[i] += 1
    return [(name, t / 10) for (name, _), t in zip(rows, tenths) if t > 0]


def render(rows, repo_count):
    repos = "repo" if repo_count == 1 else "repos"
    lines = [
        "//! Generated by scripts/update_languages.py. Don't edit by hand: the",
        "//! weekly workflow overwrites it.",
        "",
        "use crate::content::Language;",
        "",
        "/// Shown above the language bar",
        f'pub const LANGUAGES_CAPTION: &str = "languages · {repo_count} public {repos}";',
        "",
        "pub const LANGUAGES: &[Language] = &[",
    ]
    for name, share in rows:
        color = FALLBACK if name == "Other" else COLORS.get(name, FALLBACK)
        lines.append(f'    Language {{ name: "{name}", share: {share:.1f}, color: "{color}" }},')
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    if len(sys.argv) == 2:  # Testing: read {"repos": n, "languages": {"Lang": bytes}} instead
        data = json.loads(Path(sys.argv[1]).read_text())
        totals, count = data["languages"], data["repos"]
    else:
        totals, count = fetch()
    if not totals:
        sys.exit("No language data found; leaving src/languages.rs as it is")
    OUT.write_text(render(shares(totals), count))
    print(OUT.read_text())


if __name__ == "__main__":
    main()
